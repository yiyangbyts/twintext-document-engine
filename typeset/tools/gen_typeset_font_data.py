"""Generate core/font-data.js from BabelDOC 0.6.4's glyph list and Latin encodings (Adobe Glyph List; pdfminer.six tables)."""
import json
from pathlib import Path
from babeldoc.format.pdf.new_parser.runtime.font_encoding_runtime import EncodingDB
from babeldoc.format.pdf.new_parser.runtime.data.glyphlist import glyphname2unicode
pack = lambda table: {str(k): v for k, v in sorted(table.items())}
source = f"""// Generated by scripts/gen_typeset_font_data.py from BabelDOC 0.6.4 (Adobe Glyph List; Latin encodings from pdfminer.six).
// SPDX-License-Identifier: AGPL-3.0-only
(function(global){{
  'use strict';
  global.TwinTextTypesetFontData=Object.freeze({{
    GLYPHS:{json.dumps(glyphname2unicode, ensure_ascii=False, separators=(',', ':'), sort_keys=True)},
    ENCODINGS:{{Standard:{json.dumps(pack(EncodingDB.std2unicode), ensure_ascii=False, separators=(',', ':'))},
      MacRoman:{json.dumps(pack(EncodingDB.mac2unicode), ensure_ascii=False, separators=(',', ':'))},
      WinAnsi:{json.dumps(pack(EncodingDB.win2unicode), ensure_ascii=False, separators=(',', ':'))},
      PDFDoc:{json.dumps(pack(EncodingDB.pdf2unicode), ensure_ascii=False, separators=(',', ':'))}}}
  }});
}})(this);
"""
Path('core/font-data.js').write_text(source, encoding='utf8')

# Control boxes of the base-14 fonts by WinAnsi code, as BabelDOC's table gives them.
from babeldoc.format.pdf.babelpdf import base14
table = {family: base14.get_base14_bbox(family) for family in {*base14.base14_bbox, *base14.win_core}}
compact = {family: {str(code): [round(float(v), 3) for v in box] for code, box in enumerate(boxes) if any(box)} for family, boxes in table.items()}
source = Path('core/font-data.js').read_text(encoding='utf8')
source = source.replace("    ENCODINGS:{Standard:", "    BASE14:" + json.dumps(compact, separators=(',', ':')) + ",\n    BASE14_ALIAS:" + json.dumps(base14.base14_alias, separators=(',', ':')) + ",\n    ENCODINGS:{Standard:")
Path('core/font-data.js').write_text(source, encoding='utf8')

# Which characters the target fonts can draw, and the font-name rules for formulas, as BabelDOC decides them for Chinese output.
import re
import pymupdf
from babeldoc.assets import assets
from babeldoc.format.pdf.document_il.utils import formular_helper
family = assets.get_font_family('zh-CN')
names = []
for key in ('normal', 'script', 'fallback', 'base'):
    for name in family[key]:
        if name not in names: names.append(name)
fonts = [pymupdf.Font(fontfile=str(assets.get_font_and_metadata(name)[0])) for name in names]
ranges = []; start = None
for code in range(0x110000):
    present = any(font.has_glyph(code) for font in fonts)
    if present and start is None: start = code
    if not present and start is not None: ranges += [start, code - 1]; start = None
if start is not None: ranges += [start, 0x10ffff]
text = Path(formular_helper.__file__).read_text(encoding='utf8')
def pattern(name):
    block = text[text.index(name + ' = ('):]
    block = block[:re.search(r'\n\s+\)', block).start()]
    return ''.join(eval(line.strip()) for line in block.split('\n')[1:] if line.strip().startswith('r"'))
source = Path('core/font-data.js').read_text(encoding='utf8')
source = source.replace("    GLYPHS:", "    COVERAGE:" + json.dumps(ranges, separators=(',', ':')) + ",\n    FORMULA_FONTS:" + json.dumps({'precise': pattern('precise_formula_font_pattern'), 'text': pattern('pattern_text'), 'broad': pattern('broad_formula_font_pattern')}, separators=(',', ':')) + ",\n    GLYPHS:", 1)
Path('core/font-data.js').write_text(source, encoding='utf8')
print('fonts', len(names), 'ranges', len(ranges) // 2)

# Core-14 metrics: BabelDOC measures these fonts from the table even when the file gives widths.
from babeldoc.format.pdf.new_parser.runtime.data.fontmetrics import FONT_METRICS
metrics = {name: {'name': d.get('FontName', name), 'descent': d.get('Descent', 0), 'missing': d.get('MissingWidth', 0), 'widths': w} for name, (d, w) in FONT_METRICS.items()}
source = Path('core/font-data.js').read_text(encoding='utf8')
source = source.replace("    GLYPHS:", "    METRICS:" + json.dumps(metrics, ensure_ascii=False, separators=(',', ':')) + ",\n    GLYPHS:", 1)
Path('core/font-data.js').write_text(source, encoding='utf8')

# What the typesetter needs from BabelDOC: its line-break class, and the fonts the package carries, in BabelDOC's order, with their facts.
from babeldoc.format.pdf.document_il.midend import typesetting as ts
from babeldoc.assets import embedding_assets_metadata as am
pattern_text = re.sub(r'\\U000([0-9A-Fa-f]{5})', lambda m: '\\u{' + m.group(1) + '}', ts.LINE_BREAK_REGEX.pattern)
carried = sorted(p.name for p in Path('assets/fonts').glob('*.ttf'))
order = {k: [n for n in family[k] if n in carried] for k in ('script', 'normal', 'fallback', 'base')}
facts = {n: {k: am.EMBEDDING_FONT_METADATA[n][k] for k in ('ascent', 'descent', 'bold', 'italic', 'serif', 'font_name')} for n in carried}
source = Path('core/font-data.js').read_text(encoding='utf8')
source = source.replace("    GLYPHS:", "    LINE_BREAK:" + json.dumps(pattern_text) + ",\n    FONT_FAMILY:" + json.dumps(order, separators=(',', ':')) + ",\n    FONT_FACTS:" + json.dumps(facts, ensure_ascii=False, separators=(',', ':')) + ",\n    GLYPHS:", 1)
Path('core/font-data.js').write_text(source, encoding='utf8')
